function LegalText({ text }) {
  const blocks = text.split(/\n\s*\n/).filter(Boolean);

  return blocks.map((block) => {
    const value = block.trim();

    if (TOP_LEVEL_IDS[value]) {
      return (
        <h2 key={value} id={TOP_LEVEL_IDS[value]}>
          {value}
        </h2>
      );
    }

    if (SUBHEADINGS.has(value)) {
      return <h3 key={value}>{value}</h3>;
    }

    if (value.startsWith("•")) {
      return (
        <ul key={value.slice(0, 45)}>
          {value
            .split("\n")
            .filter(Boolean)
            .map((item) => (
              <li key={item}>{item.replace(/^•\s*/, "")}</li>
            ))}
        </ul>
      );
    }

    return <p key={value.slice(0, 70)}>{value}</p>;
  });
}

